import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
await mkdir(".qa.local/lemma-motion", { recursive: true });
try {
  await page.goto("http://localhost:1427/tests/lemma-preview.html", { waitUntil: "domcontentloaded", timeout: 60000 });
  await page.locator('.lemma-wardrobe-preview [data-renderer="3d"]').waitFor();
  const checks = await page.evaluate(async () => {
    const { createCompanionMotion } = await import("/src/features/lemma/motion.ts");
    const input = { dt: 1 / 60, now: 0, mood: "idle", personality: "standard", x: 1, y: 0, hovered: false, focused: false, enabled: true, movement: 1, notice: null };
    const sample = (director, count, change = {}) => { let pose; for (let i = 0; i < count; i++) pose = director.tick({ ...input, now: i / 60, ...change }); return pose; };
    const tracking = createCompanionMotion();
    const lead = sample(tracking, 8), turned = sample(tracking, 150);
    const secondary = lead.sway;
    let overshoot = false;
    for (let i = 0; i < 180; i++) if (tracking.tick({ ...input, x: 0, now: 3 + i / 60 }).bodyX < -0.001) overshoot = true;
    const settled = sample(tracking, 300, { x: 0 });
    const quiet = sample(createCompanionMotion(), 150, { focused: true });
    const disabled = sample(createCompanionMotion(), 150, { enabled: false, hovered: true, notice: { x: 1, y: 0 } });
    const hover = sample(createCompanionMotion(), 120, { hovered: true });
    const thought = sample(createCompanionMotion(), 50, { mood: "thinking" });
    const panel = { x: 1, y: -1 }, aware = createCompanionMotion();
    const noticed = sample(aware, 120, { x: 0, notice: panel });
    let glanceFinished;
    for (let i = 0; i < 240; i++) glanceFinished = aware.tick({ ...input, now: 2 + i / 60, x: 0, notice: panel });
    const styles = ["standard", "cheerful", "calm", "direct", "witty", "coach"].map(personality => sample(createCompanionMotion(), 10, { personality }).bodyX);
    const greeting = createCompanionMotion(); greeting.greet(0);
    const welcome = greeting.tick({ ...input, now: 0.6 }); greeting.greet(2);
    const rateLimited = greeting.tick({ ...input, now: 2.5 });
    const tap = createCompanionMotion(); tap.tap(0); const clicked = tap.tick({ ...input, now: 0.3 });
    const focus = createCompanionMotion(); focus.tick({ ...input, focused: true }); focus.tick({ ...input, now: 1 });
    const complete = focus.tick({ ...input, now: 1.5 });
    const speech = createCompanionMotion(); speech.tick({ ...input, mood: "speaking" });
    const talking = speech.tick({ ...input, mood: "speaking", now: 0.35 });
    const pause = speech.tick({ ...input, mood: "speaking", now: 2 });
    return { lead, turned, secondary, overshoot, settled, quiet, disabled, hover, thought, noticed, glanceFinished, styles, welcome, rateLimited, clicked, complete, talking, pause };
  });
  assert.ok(checks.lead.eyeX > checks.lead.bodyX * 1.5, "Eyes lead the body");
  assert.ok(checks.turned.bodyX > 0.95 && checks.secondary < 0, "Body catches up; accessories trail");
  assert.ok(checks.overshoot && Math.abs(checks.settled.bodyX) < 0.001, "Settles with a small overshoot");
  assert.ok(checks.quiet.bodyX < checks.turned.bodyX / 4, "Focus quiets movement");
  for (const key of ["eyeX", "eyeY", "bodyX", "bodyY", "sway", "lean", "shift", "nod", "bounce", "accessoryLift", "tilt"]) assert.equal(checks.disabled[key], 0, `Reduced motion: ${key}`);
  assert.ok(checks.hover.lean > 0.05 && checks.thought.eyeY < 0 && checks.thought.tilt > 0);
  assert.ok(checks.noticed.shift < 0 && checks.noticed.eyeX > 0, "Looks at nearby panels and makes space");
  assert.ok(Math.abs(checks.glanceFinished.eyeX) < 0.01 && checks.glanceFinished.shift < 0, "Glance ends while personal space is maintained");
  assert.equal(new Set(checks.styles).size, 6, "Personality changes motion timing");
  assert.ok(checks.welcome.nod > 0 && checks.welcome.bounce > 0 && !checks.rateLimited.greeting);
  assert.ok(checks.clicked.bounce > 0 && checks.complete.nod > 0);
  assert.ok(Math.abs(checks.talking.nod) > 0.01 && checks.pause.nod === 0, "Conversational gestures include rests");

  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.clock.install({ time: new Date("2026-11-07T10:00:00Z") });
  const face = page.locator('.lemma-face[role="button"]').first();
  await page.mouse.move(5, 5); await page.clock.runFor(100);
  await page.clock.fastForward(61000); await page.mouse.move(20, 20); await page.clock.runFor(400);
  assert.equal(await face.getAttribute("data-greeting"), "true", "Welcomes a returning user");
  await face.screenshot({ path: ".qa.local/lemma-motion/welcome.png" });
  await page.clock.runFor(2000);
  assert.equal(await face.getAttribute("data-greeting"), "false");
  await page.evaluate(() => window.dispatchEvent(new Event("blur")));
  await page.clock.fastForward(31000);
  await page.evaluate(() => window.dispatchEvent(new Event("focus")));
  await page.clock.runFor(400);
  assert.equal(await face.getAttribute("data-greeting"), "true", "Welcomes a return to the window");
  await page.emulateMedia({ reducedMotion: "reduce" }); await page.clock.fastForward(61000);
  await page.mouse.move(40, 40); await page.clock.runFor(400);
  assert.equal(await face.getAttribute("data-greeting"), "false", "Reduced motion suppresses greetings");
  assert.deepEqual(errors, []);
  console.log("PASS: eyes lead, spring settling, accessory inertia, six personalities, hover/tap, thinking/conversation pauses, return greeting/cooldown, focus completion, nearby panels and reduced motion");
} finally { await browser.close(); }
