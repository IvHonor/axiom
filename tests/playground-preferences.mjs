import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, reducedMotion: "reduce" });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const base = "http://localhost:1427/tests/playground-preview.html";
await mkdir(".qa.local/playground-preferences", { recursive: true });
async function open(query = "") {
  await page.goto(`${base}?persist&${query}`);
  await page.getByRole("combobox", { name: "Leaderboard participation", exact: true }).waitFor();
  await page.locator(".pg-arena").waitFor();
  await page.waitForFunction(() => window.calls.some(c => c.command === "playground_board"));
}
const sidebar = page.getByLabel("Playground preferences", { exact: true });
const participation = page.getByRole("combobox", { name: "Leaderboard participation", exact: true });
const save = page.getByRole("button", { name: "Save sharing preferences", exact: true });
try {
  await page.clock.install({ time: new Date("2026-11-16T14:00:00Z") });
  await open();
  assert.equal(await sidebar.locator(".pg-friends, .gd-garden, .pg-add").count(), 0);
  await page.getByRole("button", { name: /View friends/ }).click();
  const friends = page.getByRole("dialog", { name: "Friends", exact: true });
  await friends.waitFor();
  await page.keyboard.press("Shift+Tab");
  assert.equal(await friends.evaluate(n => n.contains(document.activeElement)), true, "focus stays inside the pop-out");
  await friends.getByRole("textbox", { name: "Add a friend by handle or friend code" }).fill("@new_friend");
  await friends.getByRole("button", { name: "Add friend", exact: true }).click();
  await friends.getByRole("status").filter({ hasText: /Asked/ }).waitFor();
  await friends.getByRole("button", { name: "Accept Mo", exact: true }).click();
  await friends.getByRole("button", { name: "Cheer Mo on", exact: true }).waitFor();
  await page.keyboard.press("Escape");
  assert.equal(await friends.count(), 0);
  assert.ok(await page.getByRole("button", { name: /View friends/ }).evaluate(n => n === document.activeElement));
  console.log("PASS: full friends pop-out, requests, adding friends, Escape and focus restoration");

  await page.getByRole("combobox", { name: "Default audience" }).selectOption("global");
  await page.waitForFunction(() => document.querySelector(".pg-address")?.textContent.includes("global"));
  assert.equal(await participation.inputValue(), "friends", "browsing global never opts you in");
  await participation.selectOption("global");
  await sidebar.locator("summary").click();
  await page.getByRole("switch", { name: "Share days active", exact: true }).click();
  await save.click();
  await page.waitForFunction(() => window.calls.some(c => c.command === "playground_save" && c.args.global === true && !c.args.shared.includes("active")));
  await page.waitForFunction(() => document.querySelector(".pg-pref-profile")?.textContent.includes("Friends + Global"));
  assert.equal(await save.isDisabled(), true);
  await page.evaluate(() => { window.playgroundMock.holdRefresh(); void window.refreshPlayground(); });
  await participation.selectOption("off");
  await save.click();
  const leave = page.getByRole("dialog", { name: "Leave leaderboards?", exact: true });
  await leave.waitFor();
  assert.equal(await page.evaluate(() => window.calls.filter(c => c.command === "playground_leave").length), 0);
  await leave.getByRole("button", { name: "Cancel", exact: true }).click();
  await save.click();
  await leave.getByRole("button", { name: "Leave leaderboards", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".pg-pref-profile")?.textContent.includes("Not sharing"));
  await page.evaluate(() => window.playgroundMock.releaseRefresh());
  await page.waitForTimeout(80);
  assert.ok((await sidebar.locator(".pg-pref-profile").textContent()).includes("Not sharing"), "a stale refresh cannot restore old participation");
  await page.locator(".pg-arena .pg-podium").first().waitFor();
  assert.equal(await page.locator(".pg-arena [data-you]").count(), 0, "off removes your public scores but keeps boards visible");
  console.log("PASS: separate viewing/consent, selective sharing, confirmed opt-out and browsing after leaving");

  await page.getByRole("combobox", { name: "Default activity" }).selectOption("daily_plan.done");
  assert.equal(await page.getByRole("combobox", { name: "Default audience" }).inputValue(), "friends");
  assert.equal(await page.getByRole("combobox", { name: "Default audience" }).locator('option[value="global"]').isDisabled(), true);
  await page.getByRole("combobox", { name: "Default period" }).selectOption("month");
  for (const name of ["Compact rows", "Show companions", "Show podium", "Reduce animations"]) await page.getByRole("switch", { name, exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".pg-view")?.hasAttribute("data-reduced-motion"));
  assert.equal(await page.locator(".pg-stage").count(), 0);
  assert.ok(await page.locator(".pg-ranks .pg-row").count());
  assert.equal(await page.locator(".pg-view").getAttribute("data-no-companions"), "true");
  await page.reload();
  await page.locator(".pg-arena").waitFor();
  assert.equal(await participation.inputValue(), "off");
  assert.equal(await page.getByRole("switch", { name: "Compact rows", exact: true }).getAttribute("aria-checked"), "true");
  await page.waitForFunction(() => document.querySelector(".pg-address")?.textContent.includes("daily_plan.done?month"));
  console.log("PASS: live filters, friends-only metrics, compact rows, companions, podium, reduced motion and saved defaults");

  // Restore a participant for alert comparisons; first data is a quiet baseline.
  await participation.selectOption("friends");
  await sidebar.locator("summary").click();
  await page.getByRole("switch", { name: "Share days active", exact: true }).click();
  await save.click();
  await page.waitForFunction(() => document.querySelector(".pg-pref-profile")?.textContent.includes("Friends only"));
  await page.getByRole("combobox", { name: "Default activity" }).selectOption("active");
  await page.getByRole("combobox", { name: "Default period" }).selectOption("week");
  await page.waitForFunction(() => document.querySelector(".pg-address")?.textContent.includes("active?week"));
  await page.waitForTimeout(100);
  await page.evaluate(() => window.playgroundMock.rank(4));
  await page.getByRole("button", { name: "Refresh", exact: true }).click();
  await page.getByLabel("Playground alerts", { exact: true }).getByText(/rank moved from #2 to #4/).waitFor();
  await page.evaluate(() => window.playgroundMock.cheerYou());
  await page.getByRole("button", { name: /View friends/ }).click();
  await page.keyboard.press("Escape");
  await page.getByLabel("Playground alerts", { exact: true }).getByText(/Sam cheered you/).waitFor();
  await page.getByRole("switch", { name: "Cheers from friends", exact: true }).click();
  assert.equal(await page.getByLabel("Playground alerts", { exact: true }).getByText(/Sam cheered you/).count(), 0);
  await page.clock.setSystemTime(new Date("2026-11-23T14:00:00Z"));
  await page.getByRole("button", { name: "Refresh", exact: true }).click();
  await page.getByLabel("Playground alerts", { exact: true }).getByText(/won last week/).waitFor();
  console.log("PASS: rank, cheer and new-period alerts; individual alert switches work");

  await page.getByRole("combobox", { name: "Starting page", exact: true }).selectOption("hub");
  await page.reload();
  await page.getByRole("tab", { name: "Nexus", exact: true }).waitFor();
  assert.equal(await page.getByRole("tab", { name: "Nexus", exact: true }).getAttribute("aria-selected"), "true");
  await page.getByRole("combobox", { name: "Starting page", exact: true }).selectOption("boards");
  await page.reload();
  await page.locator(".pg-arena").waitFor();
  await page.screenshot({ path: ".qa.local/playground-preferences/sidebar.png", fullPage: true });
  console.log("PASS: starting-page preference applies on opening Playground");
  await open("slowpublish");
  await page.waitForFunction(() => window.calls.some(c => c.command === "playground_publish"));
  await participation.selectOption("off");
  await save.click();
  await page.getByRole("dialog", { name: "Leave leaderboards?", exact: true }).getByRole("button", { name: "Leave leaderboards", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".pg-pref-sharing")?.getAttribute("aria-busy") === "true");
  assert.equal(await page.evaluate(() => window.calls.some(c => c.command === "playground_leave")), false, "consent changes wait for the old publish");
  await page.evaluate(() => window.playgroundMock.releasePublish());
  await page.waitForFunction(() => document.querySelector(".pg-pref-profile")?.textContent.includes("Not sharing"));
  assert.equal(await page.evaluate(() => {
    const left = window.calls.findIndex(c => c.command === "playground_leave");
    return window.calls.slice(left + 1).some(c => c.command === "playground_save" || c.command === "playground_publish");
  }), false, "an old publisher cannot restore consent or publish after leaving");
  await open("saveerror");
  const status = await sidebar.locator(".pg-pref-profile").textContent();
  await participation.selectOption("global");
  await save.click();
  await sidebar.getByRole("alert").filter({ hasText: "Could not save" }).waitFor();
  assert.equal(await sidebar.locator(".pg-pref-profile").textContent(), status);
  assert.equal(await save.isDisabled(), false);
  console.log("PASS: in-flight publication cannot undo opt-out; failed saves preserve the current sharing status");
  for (const width of [240, 375]) {
    await page.setViewportSize({ width, height: 800 });
    await page.goto(`${base}?sidebar`);
    await participation.waitFor();
    assert.equal(await sidebar.evaluate(n => n.scrollWidth <= n.clientWidth + 1), true);
    await page.getByRole("button", { name: /View friends/ }).click();
    await friends.waitFor();
    assert.equal(await friends.evaluate(n => {
      const rect = n.getBoundingClientRect();
      return rect.left >= 0 && rect.right <= innerWidth && n.scrollWidth <= n.clientWidth + 1;
    }), true, `friends pop-out fits ${width}px`);
    await page.keyboard.press("Escape");
  }
  console.log("PASS: preferences and friends dialog fit narrow screens");
  assert.deepEqual(errors, []);
} finally { await browser.close(); }
