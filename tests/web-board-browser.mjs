import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

export async function checkBoard({ page, accounts, area, until, today, tomorrow }) {
  const rows = table => [...accounts.get('a').rows.values()].filter(row => row.table === 'project_board_' + table && !row.data.deleted_at);
  const dialog = () => page.getByRole('dialog');
  const view = name => page.getByRole('navigation', { name: 'Project view' }).getByRole('button', { name, exact: true });
  const card = id => page.getByTestId('board-card-' + id);
  await area('Project Board').click();
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await dialog().getByLabel('Project name', { exact: true }).fill('Web release');
  await dialog().getByRole('button', { name: 'Create project', exact: true }).click();
  await until(() => rows('projects').some(row => row.data.name === 'Web release'), 'project did not sync');
  const project = rows('projects').find(row => row.data.name === 'Web release');
  await until(() => rows('columns').filter(row => row.data.project_id === project.id).length === 4, 'default columns did not sync');
  const column = name => rows('columns').find(row => row.data.project_id === project.id && row.data.name === name);
  await page.getByRole('button', { name: 'New card', exact: true }).click();
  await dialog().getByLabel('Card title', { exact: true }).fill('Build the browser board');
  await dialog().getByLabel('Card description', { exact: true }).fill('Personal boards sync with the desktop.');
  await dialog().getByLabel('Priority', { exact: true }).selectOption('3');
  await dialog().getByLabel('Start date', { exact: true }).fill(today);
  await dialog().getByLabel('Due date', { exact: true }).fill(tomorrow);
  await dialog().getByLabel('Estimate (hours)', { exact: true }).fill('1.5');
  await dialog().getByLabel('Repeat', { exact: true }).selectOption('weekly');
  await dialog().getByRole('button', { name: 'Save card', exact: true }).click();
  await until(() => rows('tasks').some(row => row.data.project_id === project.id), 'new card did not sync');
  const task = rows('tasks').find(row => row.data.project_id === project.id);
  assert.equal(task.data.priority, 3); assert.equal(task.data.estimate, 1.5); assert.equal(task.data.due_date, tomorrow);
  await page.getByRole('button', { name: 'Labels', exact: true }).click();
  await dialog().getByLabel('Label name', { exact: true }).fill('Release');
  await dialog().getByRole('button', { name: 'Add label', exact: true }).click();
  await until(() => rows('labels').some(row => row.data.project_id === project.id), 'label did not sync');
  const label = rows('labels').find(row => row.data.project_id === project.id);
  await dialog().getByRole('button', { name: 'Close dialog', exact: true }).click();
  await card(task.id).getByRole('button', { name: 'Build the browser board', exact: true }).click();
  await dialog().getByRole('checkbox', { name: 'Label Release', exact: true }).click();
  await until(() => rows('task_labels').some(row => row.data.task_id === task.id && row.data.label_id === label.id), 'card label did not sync');
  for (const value of ['Review changes', 'Ship changes']) {
    await dialog().getByLabel('New checklist item', { exact: true }).fill(value);
    await dialog().getByRole('button', { name: 'Add item', exact: true }).click();
    await until(() => rows('checklist_items').some(row => row.data.text === value), 'checklist item did not sync');
  }
  await dialog().getByLabel('Edit checklist Ship changes', { exact: true }).fill('Ship tested changes');
  await dialog().getByRole('button', { name: 'Save checklist Ship changes', exact: true }).click();
  await until(() => rows('checklist_items').some(row => row.data.task_id === task.id && row.data.text === 'Ship tested changes'), 'checklist text edit did not save');
  await dialog().getByRole('checkbox', { name: 'Checklist Review changes', exact: true }).click();
  await until(() => rows('checklist_items').find(row => row.data.text === 'Review changes')?.data.done, 'checklist completion did not sync');
  await dialog().getByRole('button', { name: 'Make subtask', exact: true }).first().click();
  await until(() => rows('tasks').some(row => row.data.parent_task_id === task.id && row.data.title === 'Review changes'), 'checklist conversion did not create a subtask');
  const child = rows('tasks').find(row => row.data.parent_task_id === task.id);
  assert.equal(child.data.column_id, column('Done').id); assert.ok(child.data.completed_at);
  await dialog().getByLabel('Template name', { exact: true }).fill('Release recipe');
  await dialog().getByRole('button', { name: 'Save as template', exact: true }).click();
  await until(() => rows('templates').some(row => row.data.project_id === project.id), 'template did not sync');
  await dialog().getByRole('button', { name: 'Close dialog', exact: true }).click();
  console.log('PASS: board project/card creation, rich fields, labels, checklist conversion and templates');

  await page.getByRole('button', { name: 'New column', exact: true }).click();
  await dialog().getByLabel('Column name', { exact: true }).fill('Review');
  await dialog().getByLabel('Work-in-progress limit (optional)', { exact: true }).fill('1');
  await dialog().getByRole('button', { name: 'Save column', exact: true }).click();
  await until(() => !!column('Review'), 'custom column did not sync');
  await page.getByRole('button', { name: 'Move column Review left', exact: true }).click();
  await until(() => column('Review').data.position < column('Done').data.position, 'column reordering did not sync');
  await view('Table').click();
  await page.getByLabel('Status for Build the browser board', { exact: true }).selectOption(column('Review').id);
  await until(() => task.data.column_id === column('Review').id, 'table column move did not sync');
  await view('Board').click();
  await page.getByTestId('board-column-' + column('Review').id).getByText('Work-in-progress limit reached.', { exact: true }).waitFor();
  await page.getByLabel('Filter label', { exact: true }).selectOption(label.id);
  assert.equal(await page.getByRole('article', { name: 'Card Review changes', exact: true }).count(), 0, 'label filter hides unrelated cards');
  await page.getByLabel('Filter label', { exact: true }).selectOption('');
  // Use native drag-and-drop so move and recurrence are verified through the actual board UI.
  await page.getByTestId('board-column-' + column('Done').id).evaluate(node => { node.parentElement.scrollLeft = node.parentElement.scrollWidth; });
  await card(task.id).dragTo(page.getByTestId('board-column-' + column('Done').id), { sourcePosition: { x: 30, y: 20 }, targetPosition: { x: 100, y: 50 } });
  await until(() => task.data.column_id === column('Done').id && !!task.data.completed_at, 'dragging to Done did not complete the card');
  await until(() => rows('tasks').some(row => row.id !== task.id && row.data.project_id === project.id && row.data.title === 'Build the browser board'), 'completing a recurring card did not create the next occurrence');
  const next = rows('tasks').find(row => row.id !== task.id && row.data.project_id === project.id && row.data.title === 'Build the browser board');
  assert.equal(next.data.recurrence, 'weekly'); assert.equal(task.data.recurrence, null);
  assert.ok(rows('checklist_items').some(row => row.data.task_id === next.id && row.data.text === 'Ship tested changes' && !row.data.done));
  await card(task.id).getByRole('button', { name: 'Build the browser board', exact: true }).click();
  await dialog().getByRole('button', { name: 'Archive card', exact: true }).click();
  await until(() => task.data.archived, 'archive did not sync');
  await view('Archive').click(); await card(task.id).getByRole('button', { name: 'Build the browser board', exact: true }).click();
  await dialog().getByRole('button', { name: 'Restore card', exact: true }).click(); await until(() => !task.data.archived, 'restore did not sync');
  await view('Timeline').click();
  await page.getByRole('button', { name: `Schedule Build the browser board: ${today} to ${tomorrow}`, exact: true }).waitFor();
  await view('Insights').click(); await page.getByRole('heading', { name: 'Eight weeks of completion', exact: true }).waitFor();
  await view('Activity').click(); await page.getByText('Completed', { exact: true }).waitFor();
  console.log('PASS: custom columns/WIP, table moves, native dragging, recurrence copies, archive/restore, timeline, activity and insights');

  await view('Templates').click();
  await page.getByRole('button', { name: 'Create from template', exact: true }).click();
  await dialog().getByLabel('Card title', { exact: true }).fill('Card from reusable recipe');
  await dialog().getByRole('button', { name: 'Save card', exact: true }).click();
  await until(() => rows('tasks').some(row => row.data.title === 'Card from reusable recipe'), 'template card did not save');
  await view('Board').click();
  await card(next.id).getByRole('button', { name: 'Plan today', exact: true }).click();
  await until(() => [...accounts.get('a').rows.values()].some(row => row.table === 'daily_plan_tasks' && row.data.board_task_id === next.id), 'board Plan today did not link Daily Plan');
  await page.getByRole('button', { name: 'Project settings', exact: true }).click();
  await dialog().getByLabel('Project name', { exact: true }).fill('Web release updated');
  await dialog().getByRole('button', { name: 'Save project', exact: true }).click(); await until(() => project.data.name === 'Web release updated', 'project rename did not save');
  // Deleting a project requires its name and only removes that project's records.
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await dialog().getByLabel('Project name', { exact: true }).fill('Disposable project');
  await dialog().getByRole('button', { name: 'Create project', exact: true }).click();
  await until(() => rows('projects').some(row => row.data.name === 'Disposable project'), 'disposable project did not save');
  const disposable = rows('projects').find(row => row.data.name === 'Disposable project');
  await page.getByRole('button', { name: 'Project settings', exact: true }).click();
  assert.equal(await dialog().getByRole('button', { name: 'Delete project', exact: true }).isDisabled(), true);
  await dialog().getByLabel('Confirm project deletion', { exact: true }).fill('Disposable project');
  await dialog().getByRole('button', { name: 'Delete project', exact: true }).click();
  await until(() => !!disposable.data.deleted_at, 'project deletion did not sync');
  assert.equal(rows('columns').filter(row => row.data.project_id === disposable.id).length, 0);
  assert.equal(project.data.deleted_at, null);
  // Filters and cards continue to work after a real production-page reload.
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByLabel('Choose project', { exact: true }).selectOption(project.id);
  await card(task.id).waitFor();
  await mkdir('.qa.local/terminal', { recursive: true });
  await page.screenshot({ path: '.qa.local/terminal/project-board.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  const sidebar = page.getByRole('complementary', { name: 'Workspace navigation' }); if (await sidebar.isVisible()) await page.getByRole('button', { name: 'Toggle sidebar', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'board scroll stays inside the page on phones');
  await page.screenshot({ path: '.qa.local/terminal/project-board-phone.png' });
  await page.setViewportSize({ width: 1440, height: 960 });
  if (!(await sidebar.isVisible())) await page.getByRole('button', { name: 'Toggle sidebar', exact: true }).click();
  await area('Daily Plan').click(); const todayButton = page.locator('.dp-toolbar').getByRole('button', { name: 'Today', exact: true }); if (await todayButton.isEnabled()) await todayButton.click();
  console.log('PASS: template creation, board-to-planner links, project editing, reload and phone width');
}
